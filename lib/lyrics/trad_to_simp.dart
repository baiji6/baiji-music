/// 转换入口（纯函数，便于单测）。
///
/// 返回**等长**的简体文本：所有替换都是 1 字对 1 字（词组表也全部等长），
/// 因此逐字时间轴的下标可以直接复用，不会错位。
String tradToSimp(String input) {
  if (input.isEmpty) return input;
  _ensureLoaded();
  // 快速路径：整段没有需要转换的字 → 原样返回（绝大多数简体歌词走这里）。
  var hasTrad = false;
  for (var i = 0; i < input.length; i++) {
    final cp = input.codeUnitAt(i);
    if (cp < _minCp || cp > _maxCp) continue;
    if (_charTable![cp - _minCp] != 0 || _phraseHeads!.contains(cp)) {
      hasTrad = true;
      break;
    }
  }
  if (!hasTrad) return input;

  final buf = StringBuffer();
  final n = input.length;
  var i = 0;
  while (i < n) {
    final cp = input.codeUnitAt(i);
    // 只有「可能是词组首字」时才尝试最长匹配，避免整行逐字做 substring。
    if (_phraseHeads!.contains(cp)) {
      var matched = false;
      final maxLen = math.min(_maxPhraseLen, n - i);
      for (var len = maxLen; len >= 2; len--) {
        final hit = _phraseMap![input.substring(i, i + len)];
        if (hit != null) {
          buf.write(hit);
          i += len;
          matched = true;
          break;
        }
      }
      if (matched) continue;
    }
    final to = (cp >= _minCp && cp <= _maxCp) ? _charTable![cp - _minCp] : 0;
    if (to != 0) {
      buf.writeCharCode(to);
    } else {
      buf.writeCharCode(cp);
    }
    i++;
  }
  return buf.toString();
}

/// 整份歌词转简体。
///
/// - 逐字时间轴按原字符下标切分（转换等长，时间完全不变）；
/// - 万一出现长度变化（表外的异常数据）→ 该行降级为整行扫光，绝不错位；
/// - 没有任何字需要转换时返回**原对象**，零分配。
Lyrics tradToSimpLyrics(Lyrics source) {
  if (source.isEmpty) return source;
  var changed = false;
  var degraded = false;
  final out = <LyricLine>[];
  for (final line in source.lines) {
    final oldText = line.displayText;
    final newText = tradToSimp(oldText);
    if (newText == oldText) {
      out.add(line);
      continue;
    }
    changed = true;
    var words = const <LyricWord>[];
    if (line.words.isNotEmpty && newText.length == oldText.length) {
      final ws = <LyricWord>[];
      var cursor = 0;
      for (final w in line.words) {
        final len = w.text.length;
        ws.add(LyricWord(
          startMs: w.startMs,
          endMs: w.endMs,
          text: newText.substring(cursor, cursor + len),
        ));
        cursor += len;
      }
      words = ws;
    } else if (line.words.isNotEmpty) {
      degraded = true;
    }
    final tr = line.translation;
    out.add(LyricLine(
      startMs: line.startMs,
      endMs: line.endMs,
      text: newText,
      words: words,
      translation: tr == null || tr.isEmpty ? tr : tradToSimp(tr),
      romanization: line.romanization,
    ));
  }
  if (!changed) return source;
  return Lyrics(
    lines: out,
    hasWordTiming: source.hasWordTiming && !degraded,
    hasTranslation: source.hasTranslation,
    hasRomanization: source.hasRomanization,
  );
}

// ===== 内部表（懒加载：首次转换才构建，约 20KB 数组 + 300 条词组） =====

/// BMP 常用汉字区间（表内只收录这一段，超出范围的字符原样透传）。
const int _minCp = 0x4E00;
const int _maxCp = 0x9FFF;

List<int>? _charTable;
Map<String, String>? _phraseMap;
Set<int>? _phraseHeads;
int _maxPhraseLen = 1;

void _ensureLoaded() {
  if (_charTable != null) return;
  assert(_tradChars.length == _simpChars.length, '繁简字表长度必须一致');
  final table = List<int>.filled(_maxCp - _minCp + 1, 0);
  for (var i = 0; i < _tradChars.length; i++) {
    final t = _tradChars.codeUnitAt(i);
    if (t < _minCp || t > _maxCp) continue;
    table[t - _minCp] = _simpChars.codeUnitAt(i);
  }
  final map = <String, String>{};
  final heads = <int>{};
  var maxLen = 1;
  for (final row in _phrases.split('\n')) {
    if (row.isEmpty) continue;
    final tab = row.indexOf('\t');
    if (tab <= 0 || tab >= row.length - 1) continue;
    final key = row.substring(0, tab);
    map[key] = row.substring(tab + 1);
    heads.add(key.codeUnitAt(0));
    if (key.length > maxLen) maxLen = key.length;
  }
  _maxPhraseLen = maxLen;
  _phraseMap = map;
  _phraseHeads = heads;
  _charTable = table;
}

/// 仅供测试：强制加载并返回统计（单字表条目数、词组数）。
({int chars, int phrases}) debugTableStats() {
  _ensureLoaded();
  return (
    chars: _charTable!.where((e) => e != 0).length,
    phrases: _phraseMap!.length,
  );
}
