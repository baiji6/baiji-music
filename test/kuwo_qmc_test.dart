void main() {
  final enc = base64Decode(_encB64);
  final plain = base64Decode(_plainB64);

  group('酷我 QMC v2 · 密钥派生', () {
    test('ekey 能解出 rawKey（704 字符 Base64）', () {
      final rawKey = QmcKeyDerivation.extractRawKeyFromEkey(_ekey);
      expect(rawKey.length, 704);
      expect(() => base64Decode(rawKey), returnsNormally);
    });

    test('最终 key 长度 512 → 走 Rc4Cipher（QMC v2）', () {
      final rawKey = QmcKeyDerivation.extractRawKeyFromEkey(_ekey);
      final key = QmcKeyDerivation.deriveQmcKey(rawKey);
      expect(key.length, 512);
      expect(key.length, greaterThan(300),
          reason: '>300 字节必须是 QMC v2 的 Rc4Cipher，不能退回 MapCipher');
    });

    test('工厂按 key 长度选择正确的 cipher', () {
      final cipher = QmcKeyDerivation.createCipherFromEkey(_ekey);
      expect(cipher, isA<Rc4Cipher>());
    });
  });

  group('酷我 QMC v2 · 解密正确性', () {
    test('解密首段得到合法 FLAC 头', () {
      final cipher = QmcKeyDerivation.createCipherFromEkey(_ekey);
      final out = cipher.decrypt(Uint8List.fromList(enc), 0);
      expect(out, equals(plain));
      expect(String.fromCharCodes(out.take(4)), 'fLaC');
    });

    test('按偏移解密与整文件解密一致（seek 前提）', () {
      final cipher = QmcKeyDerivation.createCipherFromEkey(_ekey);
      final full = cipher.decrypt(Uint8List.fromList(enc), 0);
      for (final off in [1, 100, 127, 128, 5119, 5120, 5121, 6000]) {
        final part =
            cipher.decrypt(Uint8List.fromList(enc.sublist(off)), off);
        expect(part, equals(full.sublist(off)),
            reason: '偏移 $off 的分段边界处理不一致');
      }
    });

    test('分段边界前后各 16 字节都能正确解密', () {
      final cipher = QmcKeyDerivation.createCipherFromEkey(_ekey);
      final full = cipher.decrypt(Uint8List.fromList(enc), 0);
      for (final boundary in [128, 5120]) {
        final before = cipher.decrypt(
            Uint8List.fromList(enc.sublist(boundary - 16, boundary)),
            boundary - 16);
        final after = cipher.decrypt(
            Uint8List.fromList(enc.sublist(boundary, boundary + 16)), boundary);
        expect(before, equals(full.sublist(boundary - 16, boundary)));
        expect(after, equals(full.sublist(boundary, boundary + 16)));
      }
    });
  });
