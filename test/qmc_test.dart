/// 复现 Rust 的 `(b'a'..=b'z').chain(b'A'..=b'Z').chain(b'0'..=b'9').cycle().take(n)`。
List<int> _alnumKey(int n) {
  final chars = [
    for (var c = 0x61; c <= 0x7A; c++) c, // a-z
    for (var c = 0x41; c <= 0x5A; c++) c, // A-Z
    for (var c = 0x30; c <= 0x39; c++) c, // 0-9
  ];
  return [for (var i = 0; i < n; i++) chars[i % chars.length]];
}

/// Rust 的 `(1..=len).map(|i| i as u8)`，注意超过 255 会截断。
List<int> _seqKey(int len) =>
    [for (var i = 1; i <= len; i++) i & 0xFF];

Uint8List _bytes(List<int> v) => Uint8List.fromList(v);

