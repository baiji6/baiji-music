      ]);
      for (var i = 0; i < data.length; i++) {
        data[i] = qmc1Transform(key, data[i], 0x7FFA + i);
      }
      expect(String.fromCharCodes(data), 'hello world');
    });

    test('偏移 0x7FFF 不做回绕（Rust 用 0..=0x7FFF 闭区间）', () {
      final key = _seqKey(128);
      // 与 Rust 实测一致：0 / 0x7FFF / 0x8000 三者互不相同
